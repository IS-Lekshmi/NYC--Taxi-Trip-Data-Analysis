"""Date/time analysis"""

# Date/Time Analysis

invalid_datetime_count = 0
invalid_duration_count = 0

for chunk in pd.read_csv(
    TRIP_FILE,
    usecols=["pickup_datetime", "dropoff_datetime"],
    chunksize=BATCH_SIZE
):

    # Convert to datetime
    chunk["pickup_datetime"] = pd.to_datetime(
        chunk["pickup_datetime"],
        errors="coerce"
    )

    chunk["dropoff_datetime"] = pd.to_datetime(
        chunk["dropoff_datetime"],
        errors="coerce"
    )

    # Count invalid/missing datetime values
    invalid_datetime_count += (
        chunk["pickup_datetime"].isna() |
        chunk["dropoff_datetime"].isna()
    ).sum()

    # Calculate trip duration in minutes
    duration_minutes = (
        chunk["dropoff_datetime"]
        - chunk["pickup_datetime"]
    ).dt.total_seconds() / 60

    # Count invalid durations
    invalid_duration_count += (
        duration_minutes <= 0
    ).sum()

print(
    "Rows with missing/invalid datetime:",
    invalid_datetime_count
)

print(
    "Rows with zero/negative duration:",
    invalid_duration_count
)

